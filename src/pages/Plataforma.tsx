// behind them, so `justificacion` says exactly that instead of faking a
// personalized rationale. Real feedback: adding always dumped the course
// into one fixed bucket with no say over how it should read — now the
// person picks the tipo themselves (see BranchPickButton), and each lands
// accordingly:
//   - "principal": appended to rama_principal itself.
//   - "repaso": appended to rama_repaso (created — always named exactly
//     "¿Necesitás repasar algo?", same fixed name api/roadmap.ts uses for
//     the AI-generated version — if it doesn't exist yet).
//   - "complementaria": appended to a dedicated "Agregados por vos" branch
//     (created if it doesn't exist) — kept separate from the AI's own
//     ramas_complementarias so "the AI picked this for you" and "you
//     picked this yourself" stay visually distinct.
const MANUAL_BRANCH_NAME = "Agregados por vos";
const REPASO_BRANCH_NAME = "¿Necesitás repasar algo?";

function withManualCourse(roadmap: Roadmap, courseId: string, tipo: RoadmapNodeTipo): Roadmap {
  if (roadmap.nodos.some((n) => n.id === courseId)) return roadmap; // already on the map, no-op
  const course = CATALOG.find((c) => c.id === courseId);
  if (!course) return roadmap;

  const rama = tipo === "principal" ? roadmap.ramaPrincipal.nombre : tipo === "repaso" ? REPASO_BRANCH_NAME : MANUAL_BRANCH_NAME;
  const currentNodos =
    tipo === "principal"
      ? roadmap.ramaPrincipal.nodos
      : tipo === "repaso"
        ? (roadmap.ramaRepaso?.nodos ?? [])
        : (roadmap.ramasComplementarias.find((r) => r.nombre === MANUAL_BRANCH_NAME)?.nodos ?? []);

  const newNode: RoadmapNode = {
    id: course.id,
    orden: currentNodos.length + 1,
    justificacion: "Lo agregaste vos desde el catálogo — no tiene una razón generada por la IA.",
    // The whole CatalogCourse, not just id/nombre/categoria/tipo — real
    // bug, flagged live: picking only those 4 fields silently dropped the
    // real imagen/precio/fecha/horario data this course actually has,
    // making a manually-added course look like a placeholder even when
    // the catalog had a real photo and price for it all along.
    curso: course,
    rama,
    tipo,
  };

  if (tipo === "principal") {
    return {
      ...roadmap,
      ramaPrincipal: { ...roadmap.ramaPrincipal, nodos: [...roadmap.ramaPrincipal.nodos, newNode] },
      nodos: [...roadmap.nodos, newNode],
    };
  }

  if (tipo === "repaso") {
    const ramaRepaso: RoadmapBranch = roadmap.ramaRepaso
      ? { ...roadmap.ramaRepaso, nodos: [...roadmap.ramaRepaso.nodos, newNode] }
      : { nombre: REPASO_BRANCH_NAME, nodos: [newNode] };
    return { ...roadmap, ramaRepaso, nodos: [...roadmap.nodos, newNode] };
  }

  const existing = roadmap.ramasComplementarias.find((r) => r.nombre === MANUAL_BRANCH_NAME);
  const ramasComplementarias: RoadmapBranch[] = existing
    ? roadmap.ramasComplementarias.map((r) => (r === existing ? { ...r, nodos: [...r.nodos, newNode] } : r))
    : [...roadmap.ramasComplementarias, { nombre: MANUAL_BRANCH_NAME, nodos: [newNode] }];

  return { ...roadmap, ramasComplementarias, nodos: [...roadmap.nodos, newNode] };
}

// Which branch (as a plain list of that branch's node ids) a given node
// belongs to — null if it's not found anywhere. Used by MapaBody's
// handleNodesChange to know which other cards a finished drag's new order
// needs to be compared against; the returned order doesn't matter, only
// membership does (the caller re-sorts by x itself).
function findBranchNodeIds(roadmap: Roadmap, nodeId: string): string[] | null {
  if (roadmap.ramaPrincipal.nodos.some((n) => n.id === nodeId)) {
    return roadmap.ramaPrincipal.nodos.map((n) => n.id);
  }
  if (roadmap.ramaRepaso?.nodos.some((n) => n.id === nodeId)) {
    return roadmap.ramaRepaso.nodos.map((n) => n.id);
  }
  const rama = roadmap.ramasComplementarias.find((r) => r.nodos.some((n) => n.id === nodeId));
  return rama ? rama.nodos.map((n) => n.id) : null;
}

// Re-sequences one branch to match `orderedIds` (a full permutation of
// that branch's own node ids, decided by MapaBody from current on-screen
// x-position after a drag) — reassigns "orden" 1..n to match, rebuilds the
// flat `nodos` list, and leaves every other branch untouched. Returns the
// same `roadmap` reference unchanged if `orderedIds` doesn't match any one
// branch's id set exactly (stale drag after the roadmap changed elsewhere,
// etc.) — callers use reference equality to decide whether to persist.
function withReorderedBranch(roadmap: Roadmap, orderedIds: string[]): Roadmap {
  const idSet = new Set(orderedIds);
  const reorder = (nodos: RoadmapNode[]): RoadmapNode[] | null => {
    if (nodos.length !== orderedIds.length || !nodos.every((n) => idSet.has(n.id))) return null;
    const byId = new Map(nodos.map((n) => [n.id, n]));
    return orderedIds.map((id, i) => ({ ...byId.get(id)!, orden: i + 1 }));
  };

  const principal = reorder(roadmap.ramaPrincipal.nodos);
  if (principal) {
    const ramaPrincipal = { ...roadmap.ramaPrincipal, nodos: principal };
    return {
      ...roadmap,
      ramaPrincipal,
      nodos: [...ramaPrincipal.nodos, ...(roadmap.ramaRepaso?.nodos ?? []), ...roadmap.ramasComplementarias.flatMap((r) => r.nodos)],
    };
  }

  if (roadmap.ramaRepaso) {
    const repaso = reorder(roadmap.ramaRepaso.nodos);
    if (repaso) {
      const ramaRepaso = { ...roadmap.ramaRepaso, nodos: repaso };
      return {
        ...roadmap,
        ramaRepaso,
        nodos: [...roadmap.ramaPrincipal.nodos, ...ramaRepaso.nodos, ...roadmap.ramasComplementarias.flatMap((r) => r.nodos)],
      };
    }
  }

  const idx = roadmap.ramasComplementarias.findIndex((r) => reorder(r.nodos) !== null);
  if (idx !== -1) {
    const reordered = reorder(roadmap.ramasComplementarias[idx].nodos)!;
    const ramasComplementarias = roadmap.ramasComplementarias.map((r, i) => (i === idx ? { ...r, nodos: reordered } : r));
    return {
      ...roadmap,
      ramasComplementarias,
      nodos: [...roadmap.ramaPrincipal.nodos, ...(roadmap.ramaRepaso?.nodos ?? []), ...ramasComplementarias.flatMap((r) => r.nodos)],
    };
  }

  return roadmap;
}

// A roadmap with nothing generated yet — just an empty trigger node, ready
