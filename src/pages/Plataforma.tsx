import type { PortfolioProject } from "@/components/plataforma/PortfolioView";
import { loadRoadmap, type Roadmap, type RoadmapNode } from "@/lib/ai/roadmapClient";
import { nextStatus, useRoadmapProgress, type CourseStatus } from "@/lib/roadmapProgress";

/**
 * The student platform, reached from /limbo's "Procesar resultado" button
 * (src/pages/Limbo.tsx) — its own surface with its own shell
 * (src/components/plataforma/PlataformaLayout.tsx), deliberately built from
 * scratch and independent of /limbo's UI (no shared sidebar, no shared
 * background treatment — see PlataformaLayout's own doc comment). This file
 * owns the roadmap/progress/portfolio state and decides what each of the 5
 * nav tabs renders; the shell itself is a dumb container.
 *
 *   Panel inicio / Novedades — placeholders, no prompt has specified their
 *   real content yet.
 *
 *   Plan carrera — the course roadmap node map (n8n-style), generated by
 *   /api/roadmap and handed off via sessionStorage (src/lib/ai/
 *   roadmapClient.ts), plus PlanCarreraPerfilCard alongside it: a profile
 *   summary card, NOT a phase tracker (see that component's own doc comment
 *   for why that distinction matters). The map's first node is a "trigger"
 *   node summarizing the person, not a course; transversal course picks
 *   (Softs Skills/Negocios/Producto) get a visual badge; clicking a course
 *   node opens a detail panel with real catalog data + the AI's
 *   personalized reasoning, plus a demo-only progress control
 *   (src/lib/roadmapProgress.ts).
 *
 *   Perfil — its own sub-nav (src/components/plataforma/PerfilView.tsx),
 *   Curriculum first by default:
 *     - Curriculum: auto-built once from whatever /limbo collected (the
 *       uploaded CV's text, or the conversation itself if there wasn't one
 *       — see src/lib/profileStore.ts + src/lib/cvParser.ts), no AI
 *       rewrite. Its "Certificaciones Coderhouse" section is derived live
 *       from the same roadmap progress state the map writes to.
 *     - Portfolio: fills itself with one generic placeholder project per
 *       course marked "completado" on the map (same progress state again),
 *       plus the one project the person can add by hand and/or a simulated
 *       Behance import — all three live in the same grid.
 *     - Oferta laboral: placeholder only for now, real design comes later.
 *
 *   Catálogo — a browsable replica of the real Coderhouse catalog
 *   (src/lib/catalogClient.ts reads data/course-catalog.json directly,
 *   client-side, no /api call needed for pure browsing). Search-by-name and
 *   the categoría filter are real; "Más vendidos"/"Nuevos"/"Nivel" are
 *   decorative — there's no real sales/publish-date/difficulty data for
 *   these 57 courses, so they don't filter anything rather than fake it.
 *   "Comprar" is decorative too, and never touches roadmap progress (that's
 *   Plan carrera's job only).
 *
 * "Limbo" is this session's internal codename only — it never appears in
 * user-facing copy.
 */

export default function Plataforma() {
  const roadmap = useMemo(() => loadRoadmap(), []);
  const { getStatus, getCompletedAt, advance } = useRoadmapProgress();
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [tab, setTab] = useState<PlataformaTab>("plan-carrera");

  // Portfolio state lives here (not in PortfolioView) so it survives
  // switching tabs — see PortfolioView's doc comment for why it's fine to
  // lose it on a page refresh.
  const [project, setProject] = useState<PortfolioProject | null>(null);
  const [behanceProjects, setBehanceProjects] = useState<PortfolioProject[]>([]);
  const [disponible, setDisponible] = useState(false);
  const [contacto, setContacto] = useState("");

  if (!roadmap || roadmap.nodos.length === 0) {
    return (
      <div className="flex h-screen flex-col items-center justify-center gap-4 bg-cream-soft px-6 text-center">
        <span className="flex h-14 w-14 items-center justify-center rounded-full bg-ink/5 text-ink-muted">
          <AlertCircle className="h-6 w-6" />
        </span>
        <h1 className="font-['Plus_Jakarta_Sans:SemiBold',sans-serif] text-xl text-ink">
          No encontramos tu recorrido
        </h1>
        <p className="max-w-sm font-['Inter:Regular',sans-serif] text-sm text-ink-muted">
          Puede que hayas llegado acá directo, sin pasar por la conversación. Volvé a empezar para
          armar tu recorrido.
        </p>
        <Link
          to="/limbo"
          className="rounded-pill bg-brand-hover px-6 py-3 font-['Plus_Jakarta_Sans:Medium',sans-serif] text-sm text-white transition-transform hover:scale-105"
        >
          Volver a empezar
        </Link>
      </div>
    );
  }

  return (
    <PlataformaLayout activeTab={tab} onTabChange={setTab}>
      {tab === "panel" && <PanelInicioView />}
      {tab === "plan-carrera" && (
        <>
          <PlanCarreraPerfilCard roadmap={roadmap} getStatus={getStatus} />
          <MapaBody
            roadmap={roadmap}
            getStatus={getStatus}
            advance={advance}
            selectedId={selectedId}
            setSelectedId={setSelectedId}
          />
        </>
      )}
      {tab === "catalogo" && <CatalogoView />}
      {tab === "perfil" && (
        <PerfilView
          roadmap={roadmap}
          getStatus={getStatus}
          getCompletedAt={getCompletedAt}
          project={project}
          setProject={setProject}
          behanceProjects={behanceProjects}
          setBehanceProjects={setBehanceProjects}
          disponible={disponible}
          setDisponible={setDisponible}
          contacto={contacto}
          setContacto={setContacto}
        />
      )}
      {tab === "novedades" && <NovedadesView />}
    </PlataformaLayout>
  );
}

function MapaBody({
  roadmap,
  getStatus,
  advance,
  selectedId,
  setSelectedId,
}: {
  roadmap: Roadmap;
  getStatus: (id: string) => CourseStatus;
  advance: (id: string) => void;
  selectedId: string | null;
  setSelectedId: (id: string | null) => void;
}) {
  // Recomputed whenever a status changes (getStatus's identity changes with
  // it — see useRoadmapProgress) so completed/in-progress nodes repaint.
  const { nodes, edges } = useMemo(() => buildFlow(roadmap, getStatus), [roadmap, getStatus]);

  const selectedNode = selectedId ? roadmap.nodos.find((n) => n.id === selectedId) : null;

  return (
    <div className="relative flex-1">
      <ReactFlow
        nodes={nodes}
        edges={edges}
        fitView
        fitViewOptions={{ padding: 0.3 }}
        proOptions={{ hideAttribution: true }}
        onNodeClick={(_, node) => {
          if (node.id === "trigger") return; // CAMBIO 4: panel excludes the trigger node
          setSelectedId(node.id);
        }}
      >
        <Background gap={20} />
        <Controls showInteractive={false} />
      </ReactFlow>

      {selectedNode && (
        <DetailPanel
          node={selectedNode}
          status={getStatus(selectedNode.id)}
          onAdvance={() => advance(selectedNode.id)}
          onClose={() => setSelectedId(null)}
        />
      )}
    </div>
  );
}

function DetailPanel({
  node,
  status,
  onAdvance,
  onClose,
}: {
  node: RoadmapNode;
  status: CourseStatus;
  onAdvance: () => void;
  onClose: () => void;
}) {
  const upcoming = nextStatus(status);
  const buttonLabel =
    status === "no-iniciado" ? "Marcar como en progreso" : status === "en-progreso" ? "Marcar como completado (demo)" : null;

  return (
    <div className="absolute right-0 top-0 h-full w-full max-w-sm overflow-y-auto border-l border-border-soft bg-white shadow-[-8px_0_30px_rgba(0,0,0,0.06)]">
      <div className="flex items-center justify-between border-b border-border-soft px-5 py-4">
        <span className="font-['Plus_Jakarta_Sans:SemiBold',sans-serif] text-sm text-ink">Detalle del curso</span>
        <button
          type="button"
          onClick={onClose}
          aria-label="Cerrar panel"
          className="flex h-8 w-8 items-center justify-center rounded-full text-ink-muted hover:bg-ink/5 hover:text-ink"
        >
          <X className="h-4 w-4" />
        </button>
      </div>

      {/* Block 1 — static, real catalog data only. No invented fields
          (price, schedule, difficulty, syllabus): course-catalog.json only
          has id/nombre/categoria/tipo right now, so that's all this shows. */}
      <div className="border-b border-border-soft px-5 py-5">
        {node.esTransversal && (
          <span className="mb-2 inline-block rounded-pill bg-ink/5 px-2.5 py-1 font-['Inter:Regular',sans-serif] text-[11px] uppercase tracking-wide text-ink-muted">
            Curso complementario
          </span>
        )}
        <h2 className="mb-1 font-['Plus_Jakarta_Sans:SemiBold',sans-serif] text-lg leading-snug text-ink">
          {node.curso.nombre}
        </h2>
        <p className="font-['Inter:Regular',sans-serif] text-sm text-ink-muted">
          {node.curso.categoria} · {tipoLabel(node.curso.tipo)}
        </p>
      </div>

      {/* Block 2 — visually separate: the AI's personalized "why this course,
          for this person" reasoning (CAMBIO 2/3), never the same text as a
          generic course description. */}
      <div className="bg-brand-hover/[0.04] px-5 py-5">
        <p className="mb-2 font-['Plus_Jakarta_Sans:SemiBold',sans-serif] text-xs uppercase tracking-[0.4px] text-brand-hover">
          Por qué está en tu recorrido
        </p>
        <p className="font-['Inter:Regular',sans-serif] text-[15px] leading-relaxed text-ink">{node.justificacion}</p>
      </div>

      {/* CAMBIO 5 — demo-only progress, no real payment/cursada flow. */}
      <div className="px-5 py-5">
        <p className="mb-3 flex items-center gap-2 font-['Inter:Regular',sans-serif] text-sm text-ink-muted">
          <StatusIcon status={status} />
          {statusLabel(status)}
        </p>
        {buttonLabel && (
          <button
            type="button"
            onClick={onAdvance}
            className="w-full rounded-pill bg-brand-hover px-5 py-2.5 font-['Plus_Jakarta_Sans:Medium',sans-serif] text-sm text-white transition-transform hover:scale-[1.02]"
          >
            {buttonLabel}
          </button>
        )}
        {!buttonLabel && (
          <p className="font-['Inter:Regular',sans-serif] text-xs text-ink-muted">
            Ya completaste este curso (demo) — próximo estado: {upcoming === status ? "sin cambios" : upcoming}.
          </p>
        )}
      </div>
    </div>
  );
}

function StatusIcon({ status }: { status: CourseStatus }) {
  if (status === "completado") return <CheckCircle2 className="h-4 w-4 text-green-600" />;
  if (status === "en-progreso") return <Circle className="h-4 w-4 fill-brand-hover text-brand-hover" />;
  return <Circle className="h-4 w-4 text-ink-muted" />;
}

function statusLabel(status: CourseStatus): string {
  if (status === "completado") return "Completado";
  if (status === "en-progreso") return "En progreso";
  return "No iniciado";
}

function tipoLabel(tipo: string): string {
  if (tipo === "carrera") return "Carrera";
  if (tipo === "diplomatura") return "Diplomatura";
  if (tipo === "on-demand") return "On-demand";
  return "Curso";
}

const TRIGGER_NODE_STYLE: React.CSSProperties = {
  background: "var(--color-ink, #1a1a1a)",
  color: "white",
  border: "1px solid rgba(255,255,255,0.15)",
  borderRadius: 16,
  padding: "14px 18px",
  fontFamily: "Inter, sans-serif",
  width: 240,
  boxShadow: "0 4px 20px rgba(0,0,0,0.15)",
};

function courseNodeStyle(esTransversal: boolean, status: CourseStatus): React.CSSProperties {
  const accent = esTransversal ? "#8b5cf6" : "var(--color-brand-hover, #ff5a36)";
  return {
    background: status === "completado" ? "rgba(34,197,94,0.06)" : "white",
    border: `1.5px solid ${status === "completado" ? "#22c55e" : accent}`,
    borderRadius: 16,
    padding: "12px 16px",
    fontFamily: "Inter, sans-serif",
    width: 220,
    cursor: "pointer",
    boxShadow: "0 2px 10px rgba(0,0,0,0.06)",
  };
}

function buildFlow(roadmap: Roadmap, getStatus: (id: string) => CourseStatus): { nodes: Node[]; edges: Edge[] } {
  const nodes: Node[] = [];
  const edges: Edge[] = [];
  const courseGapX = 280;

  nodes.push({
    id: "trigger",
    position: { x: 0, y: 140 },
    data: {
      label: (
        <div>
          <div className="mb-1.5 flex items-center gap-1.5 font-['Plus_Jakarta_Sans:SemiBold',sans-serif] text-xs uppercase tracking-wide text-white/70">
            <Zap className="h-3.5 w-3.5" />
            Tu perfil
          </div>
          <p className="font-['Inter:Regular',sans-serif] text-[13px] leading-snug text-white">
            {roadmap.trigger.resumen}
          </p>
        </div>
      ),
    },
    style: TRIGGER_NODE_STYLE,
    sourcePosition: Position.Right,
  });

  roadmap.nodos.forEach((node, i) => {
    const status = getStatus(node.id);
    nodes.push({
      id: node.id,
      position: { x: 300 + i * courseGapX, y: 140 },
      data: {
        label: (
          <div>
            <div className="mb-1 flex items-center justify-between gap-2">
              <span className="font-['Plus_Jakarta_Sans:SemiBold',sans-serif] text-sm text-ink">
                {node.curso.nombre}
              </span>
              <StatusIcon status={status} />
            </div>
            <span className="block font-['Inter:Regular',sans-serif] text-[11px] uppercase tracking-wide text-ink-muted">
              {tipoLabel(node.curso.tipo)} · {node.curso.categoria}
            </span>
            {node.esTransversal && (
              <span className="mt-1.5 inline-block rounded-pill bg-purple-100 px-2 py-0.5 font-['Inter:Regular',sans-serif] text-[10px] text-purple-700">
                Complementario
              </span>
            )}
          </div>
        ),
      },
      style: courseNodeStyle(node.esTransversal, status),
      sourcePosition: Position.Right,
      targetPosition: Position.Left,
    });

    const source = i === 0 ? "trigger" : roadmap.nodos[i - 1].id;
    edges.push({
      id: `e-${source}-${node.id}`,
      source,
      target: node.id,
      label: truncate(node.justificacion, 60),
      labelStyle: { fill: "var(--color-ink-muted, #666)", fontSize: 11, fontFamily: "Inter, sans-serif" },
      labelBgStyle: { fill: "var(--color-cream-soft, #fff)" },
      style: { stroke: node.esTransversal ? "#8b5cf6" : "var(--color-brand-hover, #ff5a36)" },
    });
  });

  return { nodes, edges };
}

function truncate(text: string, max: number): string {
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}
