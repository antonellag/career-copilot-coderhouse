/**
 * The student platform, reached from /limbo's "Procesar resultado" button
 * (src/pages/Limbo.tsx) — its own surface with its own shell
 * (src/components/plataforma/PlataformaLayout.tsx), deliberately built from
 * scratch and independent of /limbo's UI (no shared sidebar, no shared
 * background treatment — see PlataformaLayout's own doc comment). This file
 * owns the roadmap/progress/portfolio state and decides what each of the 5
 * nav tabs renders; the shell itself is a dumb container.
 *
 *   Panel inicio / Novedades — placeholders, no prompt has specified their
 *   real content yet.
 *
 *   Plan carrera — the course roadmap node map (n8n-style), generated by
 *   /api/roadmap and handed off via sessionStorage (src/lib/ai/
 *   roadmapClient.ts). The map's first node is a "trigger" node summarizing
 *   the person, not a course. The roadmap itself branches instead of being
 *   one flat chain: `roadmap.ramaPrincipal` is the core specialization,
 *   drawn as the horizontal trunk; `roadmap.ramasComplementarias` (Softs
 *   Skills/Negocios/Producto) each fork off their own row below the trunk,
 *   starting under the exact trunk node they `naceDesde`, with the fork
 *   edge labeled by the branch's own name and a purple dashed accent — so
 *   a complementary path reads as optional depth, not a forced step
 *   (`roadmap.nodos` stays a flat list of every node for consumers that
 *   don't care about branches — CV certifications, portfolio, this map's
 *   own search filter). Clicking a course node opens a detail panel with
 *   real catalog data + the AI's personalized reasoning, plus a demo-only
 *   progress control (src/lib/roadmapProgress.ts).
 *
 *   React Flow vs. the Figma Make reference's raw pan/zoom: kept React Flow.
 *   The reference's onMouseDown/onMouseMove/onWheel implementation does the
 *   same job (pan, zoom-to-cursor) but from scratch — React Flow already
 *   does that, PLUS everything the branching roadmap actually depends on
 *   today: edge rendering/pathfinding for the rama_principal/
 *   ramasComplementarias fork, per-node click → detail panel, and the
 *   progress-driven node restyling, all already built and verified against
 *   live Gemini output. Swapping the engine would mean rebuilding all of
 *   that on top of raw mouse events for a purely visual match with no
 *   functional gain. Instead, only the VISUAL layer was aligned to the
 *   reference: <Background variant="lines"> instead of the dot grid
 *   (matching color/spacing), and a custom pill-shaped bottom toolbar
 *   (ZoomToolbar) styled like the reference's Frame39 but wired to React
 *   Flow's own useReactFlow/useViewport hooks instead of hand-rolled state.
 *
 *   Perfil — its own sub-nav (src/components/plataforma/PerfilView.tsx),
 *   Curriculum first by default:
 *     - Curriculum: auto-built once from whatever /limbo collected (the
 *       uploaded CV's text, or the conversation itself if there wasn't one
 *       — see src/lib/profileStore.ts + src/lib/cvParser.ts), no AI
 *       rewrite. Its "Certificaciones Coderhouse" section is derived live
 *       from the same roadmap progress state the map writes to.
 *     - Portfolio: fills itself with one generic placeholder project per
 *       course marked "completado" on the map (same progress state again),
 *       plus the one project the person can add by hand and/or a simulated
 *       Behance import — all three live in the same grid.
 *     - Oferta laboral: placeholder only for now, real design comes later.
 *
 *   Catálogo — a browsable replica of the real Coderhouse catalog
 *   (src/lib/catalogClient.ts reads data/course-catalog.json directly,
 *   client-side, no /api call needed for pure browsing). Search-by-name and
 *   the categoría filter are real; "Más vendidos"/"Nuevos"/"Nivel" are
 *   decorative — there's no real sales/publish-date/difficulty data for
 *   these 57 courses, so they don't filter anything rather than fake it.
 *   "Comprar" is decorative too, and never touches roadmap progress (that's
 *   Plan carrera's job only).
 *
 * No hard gate on missing roadmap data anymore: /limbo's "Omitir test"
 * shortcut (src/pages/Limbo.tsx) jumps straight here without ever running
 * the conversation, so `loadRoadmap()` can legitimately come back null.
 * Every tab that reads roadmap data (Plan carrera, CV, Portfolio) accepts
 * `roadmap: Roadmap | null` and shows its own "todavía no cargaste nada"
 * empty state instead of the whole page refusing to render — Catálogo,
 * Panel inicio, Novedades and Oferta laboral never needed roadmap data
 * anyway, so they're unaffected either way. No manual-entry forms yet
 * (filling CV/Plan de carrera by hand) — that's a separate, bigger feature.
 *
 * "Limbo" is this session's internal codename only — it never appears in
 * user-facing copy.
 */

export default function Plataforma() {
  const roadmap = useMemo(() => loadRoadmap(), []);
  const { getStatus, getCompletedAt, advance } = useRoadmapProgress();
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [tab, setTab] = useState<PlataformaTab>("plan-carrera");

  // Portfolio state lives here (not in PortfolioView) so it survives
  // switching tabs — see PortfolioView's doc comment for why it's fine to
  // lose it on a page refresh.
  const [project, setProject] = useState<PortfolioProject | null>(null);
  const [behanceProjects, setBehanceProjects] = useState<PortfolioProject[]>([]);
  const [disponible, setDisponible] = useState(false);
  const [contacto, setContacto] = useState("");

  // Stable reference (useCallback) so it doesn't force MapaBody's useMemo
  // to recompute the whole flow on every Plataforma render. Only switches
  // the top-level tab — same level this component already owns, nothing in
  // Perfil's own internals is touched.
  const onViewPerfil = useCallback(() => setTab("perfil"), []);

  return (
    <PlataformaLayout activeTab={tab} onTabChange={setTab}>
      {tab === "panel" && <PanelInicioView />}
      {tab === "plan-carrera" && (
        <MapaBody
          roadmap={roadmap}
          getStatus={getStatus}
          advance={advance}
          selectedId={selectedId}
          setSelectedId={setSelectedId}
          onViewPerfil={onViewPerfil}
        />
      )}
      {tab === "catalogo" && <CatalogoView />}
      {tab === "perfil" && (
        <PerfilView
          roadmap={roadmap}
          getStatus={getStatus}
          getCompletedAt={getCompletedAt}
          project={project}
          setProject={setProject}
          behanceProjects={behanceProjects}
          setBehanceProjects={setBehanceProjects}
          disponible={disponible}
          setDisponible={setDisponible}
          contacto={contacto}
          setContacto={setContacto}
        />
      )}
      {tab === "novedades" && <NovedadesView />}
    </PlataformaLayout>
  );
}

function MapaBody({
  roadmap,
  getStatus,
  advance,
  selectedId,
  setSelectedId,
  onViewPerfil,
}: {
  /** Null when /limbo's "Omitir test" shortcut skipped straight here — see the module doc comment. */
  roadmap: Roadmap | null;
  getStatus: (id: string) => CourseStatus;
  advance: (id: string) => void;
  selectedId: string | null;
  setSelectedId: (id: string | null) => void;
  onViewPerfil: () => void;
}) {
  // Fixed over the canvas itself (top-right), not embedded in the shared
  // nav — see src/components/plataforma/PlataformaLayout.tsx's doc comment.
  const [query, setQuery] = useState("");

  // Recomputed whenever a status changes (getStatus's identity changes with
  // it — see useRoadmapProgress) so completed/in-progress nodes repaint.
  const { nodes: builtNodes, edges } = useMemo(
    () => buildFlow(roadmap, getStatus, onViewPerfil),
    [roadmap, getStatus, onViewPerfil],
  );

  // Real filter, not decorative. Dims (doesn't remove) non-matching course
  // nodes so the chain/edges stay legible — the trigger node is exempt,
  // it's not a course to search for.
  const nodes = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return builtNodes;
    return builtNodes.map((n) => {
      if (n.id === "trigger") return n;
      const node = roadmap?.nodos.find((rn) => rn.id === n.id);
      const matches = node?.curso.nombre.toLowerCase().includes(q) ?? false;
      return { ...n, style: { ...n.style, opacity: matches ? 1 : 0.25 } };
    });
  }, [builtNodes, query, roadmap]);

  const selectedNode = selectedId ? (roadmap?.nodos.find((n) => n.id === selectedId) ?? null) : null;

  // "Selección" (default click/drag-to-marquee) vs. "Mano" (drag-to-pan) —
  // matches Frame34's two-button toggle in the reference, and it's wired to
  // real ReactFlow behavior (panOnDrag/selectionOnDrag), not just a visual
  // toggle. Minimap visibility (the "map" icon in Frame31) is also real.
  const [tool, setTool] = useState<"select" | "hand">("hand");
  const [showMinimap, setShowMinimap] = useState(false);

  if (!roadmap) return <EmptyMapState />;

  return (
    <div className="relative flex-1">
      <ReactFlow
        nodes={nodes}
        edges={edges}
        fitView
        fitViewOptions={{ padding: 0.3 }}
        proOptions={{ hideAttribution: true }}
        minZoom={0.2}
        maxZoom={3}
        panOnDrag={tool === "hand"}
        selectionOnDrag={tool === "select"}
        onNodeClick={(_, node) => {
          if (node.id === "trigger") return; // CAMBIO 4: panel excludes the trigger node
          setSelectedId(node.id);
        }}
      >
        {/* Line grid (not dots) with the reference's exact color/spacing,
            still React Flow's own pan/zoom underneath — see the module doc
            comment for why React Flow was kept over the reference's raw
            mouse-event pan/zoom implementation. */}
        <Background variant={BackgroundVariant.Lines} gap={40} color="#E2E2E2" />
        <Panel position="top-right">
          <div className="relative">
            <Search className="pointer-events-none absolute left-4 top-1/2 h-4 w-4 -translate-y-1/2 text-ink-muted" />
            <input
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder="Buscar curso"
              className="w-56 rounded-pill border border-border-soft bg-white py-3 pl-10 pr-4 font-['Inter:Regular',sans-serif] text-sm text-ink shadow-[0_4px_16px_rgba(0,0,0,0.06)] outline-none placeholder:text-ink-muted"
            />
          </div>
        </Panel>
        {showMinimap && (
          <MiniMap
            pannable
            zoomable
            className="!rounded-2xl !border !border-border-soft"
            nodeColor={() => "#f3d9c8"}
          />
        )}
        <Panel position="bottom-center">
          <BottomToolbar tool={tool} setTool={setTool} showMinimap={showMinimap} setShowMinimap={setShowMinimap} />
        </Panel>
      </ReactFlow>

      {selectedNode && (
        <DetailPanel
          node={selectedNode}
          status={getStatus(selectedNode.id)}
          onAdvance={() => advance(selectedNode.id)}
          onClose={() => setSelectedId(null)}
        />
      )}
    </div>
  );
}

// Four separate pill/circle groups, matching the reference's Frame31
// (zoom + view controls) / Frame34 (selection-tool toggle) / Frame36
// (undo/redo) / Frame38 (help) laid out side by side by Frame39 — not one
// merged pill. Wired to React Flow's own zoom/pan engine
// (useReactFlow/useViewport) plus the real tool/minimap toggles above;
// undo/redo stay decorative since there's no edit history to walk.
function BottomToolbar({
  tool,
  setTool,
  showMinimap,
  setShowMinimap,
}: {
  tool: "select" | "hand";
  setTool: (t: "select" | "hand") => void;
  showMinimap: boolean;
  setShowMinimap: (v: boolean) => void;
}) {
  const { zoomIn, zoomOut, fitView } = useReactFlow();
  const { zoom } = useViewport();

  return (
    <div className="flex items-center gap-3">
      {/* Frame31 — zoom controls + view toggles */}
      <div className="flex items-center gap-1 rounded-pill border border-border-soft bg-white p-1.5 shadow-[0_8px_24px_rgba(0,0,0,0.1)]">
        <ToolbarButton onClick={() => zoomOut({ duration: 150 })} ariaLabel="Alejar">
          <Minus className="h-4 w-4" />
        </ToolbarButton>
        <span className="w-11 text-center font-['Inter:Regular',sans-serif] text-xs text-ink-muted">
          {Math.round(zoom * 100)}%
        </span>
        <ToolbarButton onClick={() => zoomIn({ duration: 150 })} ariaLabel="Acercar">
          <PlusIcon className="h-4 w-4" />
        </ToolbarButton>
        <div className="mx-1 h-6 w-px bg-border-soft" />
        <ToolbarButton
          onClick={() => setShowMinimap(!showMinimap)}
          ariaLabel="Mostrar minimapa"
          active={showMinimap}
        >
          <MapIcon className="h-4 w-4" />
        </ToolbarButton>
        <ToolbarButton onClick={() => fitView({ padding: 0.3, duration: 300 })} ariaLabel="Ajustar a la pantalla">
          <Maximize className="h-4 w-4" />
        </ToolbarButton>
      </div>

      {/* Frame34 — selection-tool toggle (real: panOnDrag/selectionOnDrag) */}
      <div className="flex items-center gap-1 rounded-pill border border-border-soft bg-white p-1.5 shadow-[0_8px_24px_rgba(0,0,0,0.1)]">
        <ToolbarButton onClick={() => setTool("select")} ariaLabel="Herramienta de selección" active={tool === "select"}>
          <MousePointer2 className="h-4 w-4" />
        </ToolbarButton>
        <ToolbarButton onClick={() => setTool("hand")} ariaLabel="Herramienta de mano" active={tool === "hand"}>
          <Hand className="h-4 w-4" />
        </ToolbarButton>
      </div>

      {/* Frame36 — undo/redo, decorative (no edit history exists yet) */}
      <div className="flex items-center gap-1 rounded-pill border border-border-soft bg-white p-1.5 shadow-[0_8px_24px_rgba(0,0,0,0.1)]">
        <ToolbarButton onClick={() => {}} ariaLabel="Deshacer">
          <Undo2 className="h-4 w-4" />
        </ToolbarButton>
        <ToolbarButton onClick={() => {}} ariaLabel="Rehacer">
          <Redo2 className="h-4 w-4" />
        </ToolbarButton>
      </div>

      {/* Frame38 — help, its own standalone circle */}
      <button
        type="button"
        aria-label="Ayuda"
        className="flex h-[52px] w-[52px] items-center justify-center rounded-full border border-border-soft bg-white text-ink-muted shadow-[0_8px_24px_rgba(0,0,0,0.1)] transition-colors hover:bg-ink/5 hover:text-ink"
      >
        <HelpCircle className="h-4 w-4" />
      </button>
    </div>
  );
}

function ToolbarButton({
  children,
  onClick,
  ariaLabel,
  active,
}: {
  children: React.ReactNode;
  onClick: () => void;
  ariaLabel: string;
  active?: boolean;
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      aria-label={ariaLabel}
      className={`flex h-9 w-9 items-center justify-center rounded-full transition-colors ${
        active ? "bg-brand-hover text-white" : "text-ink-muted hover:bg-ink/5 hover:text-ink"
      }`}
    >
      {children}
    </button>
  );
}

