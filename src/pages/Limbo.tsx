import { motion } from "framer-motion";
import {
  AlertCircle,
  ArrowLeft,
  ChevronLeft,
  ChevronRight,
  FileText,
  Loader2,
  Map,
  Plus,
  Send,
  Settings2,
  Wand2,
  X,
} from "lucide-react";
import { useEffect, useRef, useState } from "react";
import { Link, useNavigate } from "react-router-dom";
import { CoderhouseLogo } from "@/components/CoderhouseLogo";
import { LimboSidebar, type LimboPhase } from "@/components/limbo/LimboSidebar";
import { RiasecTest } from "@/components/limbo/RiasecTest";
import { extractPhaseComplete } from "@/lib/ai/phaseComplete";
import { useChat } from "@/lib/ai/useChat";
import type { ChatMode } from "@/lib/ai/client";
import { generateRoadmap, saveRoadmap } from "@/lib/ai/roadmapClient";
import { extractPdfText } from "@/lib/pdf/extractPdfText";
import { RIASEC_LABELS, type RiasecDimension } from "@/lib/riasec/questions";

/**
 * /limbo — the discovery agent. Independent space, reached only from the
 * hero CTA (never linked in the site navbar). Restructured into 4 sequential
 * phases per prompt-claude-code-fases-limbo.md:
 *
 *   Experiencia (chat) -> Habilidades (chat) -> Test (RIASEC cards, inline) -> Resultado
 *
 * Experiencia and Habilidades share ONE useChat instance/message thread —
 * only `mode` changes between them (see the `chatMode` derivation below), so
 * the model always has the full prior conversation in context without any
 * manual context-passing. Test is pure client-side scoring (api/chat.ts is
 * never called for it), rendered inline in this same timeline (see the
 * RiasecTest block below) instead of its own route step.
 *
 * Resultado used to close with a "Career Profile" (2-3 alternative paths)
 * generated inline in this same chat. That's gone — the result is now a
 * single ordered course roadmap rendered as a node map on /plataforma
 * (src/pages/Plataforma.tsx), generated by the separate /api/roadmap call
 * (src/lib/ai/roadmapClient.ts) once the person taps "Procesar resultado"
 * below. This chat's Resultado turn now only produces a short closing
 * message (api/_lib/prompts.ts's RESULTADO_SYSTEM_PROMPT) before that
 * button appears.
 *
 * "Limbo" is this session's internal codename only (see
 * landing-arquitectura-ia.md) — it never appears in user-facing copy here.
 */

// The real site's full category list (src/imports/1920WLight-1's Categories
// section) — same 6 categories/images/order used there, not invented.
const CATEGORIES = [
  { label: "Programación y desarrollo", image: "/limbo/categoria-programacion.png" },
  { label: "Marketing digital", image: "/limbo/categoria-marketing.png" },
  { label: "Inteligencia Artificial", image: "/limbo/categoria-ia.png", badge: "NUEVO" },
  { label: "Diseño UX/UI", image: "/limbo/categoria-uxui.png" },
  { label: "Data", image: "/limbo/categoria-data.png" },
  { label: "Negocios", image: "/limbo/categoria-negocios.png" },
];

type CvState =
  | { status: "idle" }
  | { status: "loading"; fileName: string }
  | { status: "ready"; fileName: string; text: string }
  | { status: "error"; message: string };

const CV_ERROR_MESSAGES: Record<string, string> = {
  "not-a-pdf": "Por ahora solo podemos leer archivos PDF.",
  "too-large": "El archivo pesa más de 8MB — probá con uno más liviano.",
  "empty-or-scanned":
    "No pudimos leer texto en este PDF (puede ser una imagen escaneada). Sin problema, seguimos por acá.",
  "parse-failed": "Hubo un problema al leer el PDF. Sin problema, seguimos por acá.",
};

const PHASE_TO_MODE: Record<Exclude<LimboPhase, "test">, ChatMode> = {
  experiencia: "discovery-experiencia",
  habilidades: "discovery-habilidades",
  resultado: "discovery-resultado",
};

type RoadmapState = "idle" | "loading" | "error";

export default function Limbo() {
  const navigate = useNavigate();
  const [phase, setPhase] = useState<LimboPhase>("experiencia");
  const [riasecCode, setRiasecCode] = useState<RiasecDimension[]>([]);
  const [input, setInput] = useState("");
  const [cv, setCv] = useState<CvState>({ status: "idle" });
  const [roadmapState, setRoadmapState] = useState<RoadmapState>("idle");
  const [roadmapError, setRoadmapError] = useState<string | null>(null);

  const chatMode = PHASE_TO_MODE[phase === "test" ? "experiencia" : phase];
  const { messages, send, isLoading, error } = useChat(chatMode);

  const scrollRef = useRef<HTMLDivElement>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);
  const started = useRef(false);
  const resultadoTriggered = useRef(false);

  // Advance experiencia -> habilidades -> test whenever the model's latest
  // reply is marked PHASE_COMPLETE (see api/_lib/prompts.ts).
  useEffect(() => {
    const last = messages[messages.length - 1];
    if (!last || last.role !== "assistant") return;
    const { complete } = extractPhaseComplete(last.content);
    if (!complete) return;
    if (phase === "experiencia") setPhase("habilidades");
    else if (phase === "habilidades") setPhase("test");
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [messages]);

  // Once Test finishes and we're in "resultado", auto-send the one hidden
  // turn that asks the model to close the conversation — the person doesn't
  // have to type anything to trigger this. This turn's reply is now just a
  // short closing line (see RESULTADO_SYSTEM_PROMPT); the "Procesar
  // resultado" button appears once it lands.
  useEffect(() => {
    if (phase !== "resultado" || resultadoTriggered.current || riasecCode.length === 0) return;
    resultadoTriggered.current = true;
    const dims = riasecCode.map((d) => RIASEC_LABELS[d]).join(", ");
    const apiContent = `--- Resultado test vocacional (RIASEC) ---\nDimensiones dominantes: ${dims}\n--- fin resultado test ---\n\nYa terminé el test vocacional.`;
    send("Ya terminé el test vocacional.", apiContent);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [phase, riasecCode]);

  useEffect(() => {
    scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: "smooth" });
  }, [messages]);

  const visibleMessages = messages.map((m) =>
    m.role === "assistant" ? { ...m, content: extractPhaseComplete(m.content).cleanText } : m,
  );

  const lastMessage = messages[messages.length - 1];
  const resultadoReady = phase === "resultado" && !isLoading && lastMessage?.role === "assistant";

  const handleProcessResult = async () => {
    if (roadmapState === "loading") return;
    setRoadmapState("loading");
    setRoadmapError(null);
    const transcript = messages
      .map((m) => {
        const content = m.role === "assistant" ? extractPhaseComplete(m.content).cleanText : (m.apiContent ?? m.content);
        return `${m.role === "user" ? "Persona" : "Copilot"}: ${content}`;
      })
      .join("\n\n");
    const riasecLabels = riasecCode.map((d) => RIASEC_LABELS[d]);

    try {
      const roadmap = await generateRoadmap(transcript, riasecLabels);
      saveRoadmap(roadmap);
      navigate("/plataforma");
    } catch (err) {
      setRoadmapState("error");
      setRoadmapError(err instanceof Error ? err.message : "No pudimos armar tu recorrido. Probá de nuevo.");
    }
  };

  const handleFileSelect = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    e.target.value = "";
    if (!file) return;

    setCv({ status: "loading", fileName: file.name });
    const result = await extractPdfText(file);
    if (result.ok) {
      setCv({ status: "ready", fileName: file.name, text: result.text });
    } else {
      setCv({ status: "error", message: CV_ERROR_MESSAGES[result.reason] });
    }
  };

  const startConversation = (openingMessage: string) => {
    if (started.current) return;
    started.current = true;
    const apiContent =
      cv.status === "ready"
        ? `--- CV adjunto (texto extraído) ---\n${cv.text}\n--- fin CV ---\n\n${openingMessage}`
        : undefined;
    send(openingMessage, apiContent);
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!input.trim()) return;
    if (!started.current) startConversation(input);
    else send(input);
    setInput("");
  };

  const handleCategoryClick = (label: string) => {
    startConversation(`Me interesa explorar ${label}. Contame vos por dónde empezamos.`);
  };

  return (
    <LimboShell phase={phase}>
      {messages.length === 0 && phase === "experiencia" ? (
        <div className="flex w-full min-w-0 flex-1 flex-col items-center justify-center px-6 text-center">
          <motion.h1
            initial={{ opacity: 0, y: 12 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.5 }}
            className="font-['Inter:Regular',sans-serif] text-[26px] leading-tight text-ink sm:text-[44px]"
          >
            ¡Hola! Hablemos sobre
            <br />
            tu vocación y futuro
          </motion.h1>
          <motion.p
            initial={{ opacity: 0, y: 12 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.5, delay: 0.1 }}
            className="mt-3 max-w-lg font-['Inter:Regular',sans-serif] text-sm text-ink-muted sm:text-base"
          >
            Contanos sobre vos, tu experiencia laboral, habilidades y qué te gusta, podés incluso
            adjuntar tu CV
          </motion.p>

          <motion.div
            initial={{ opacity: 0, y: 12 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.5, delay: 0.2 }}
            className="mt-10 w-full min-w-0"
          >
            <CategoryCarousel onSelect={handleCategoryClick} />
          </motion.div>
        </div>
      ) : (
        <div ref={scrollRef} className="mx-auto w-full max-w-2xl flex-1 space-y-4 overflow-y-auto px-6 py-8">
          {/* Once the CV is confirmed AND the conversation has actually
              started, its chip moves here — a one-time event in the
              timeline, at the point it happened, instead of sitting
              permanently pinned above the input like it was still
              re-uploading on every message. */}
          {cv.status === "ready" && (
            <motion.div
              initial={{ opacity: 0, y: 8 }}
              animate={{ opacity: 1, y: 0 }}
              className="mx-auto flex w-fit items-center gap-1.5 rounded-pill bg-white px-3 py-1.5 font-['Inter:Regular',sans-serif] text-xs text-ink-muted shadow-[0_1px_4px_rgba(0,0,0,0.06)]"
            >
              <FileText className="h-3.5 w-3.5 text-brand-hover" />
              {cv.fileName} adjuntado
            </motion.div>
          )}
          {visibleMessages.map((m, i) => (
            <motion.div
              key={i}
              initial={{ opacity: 0, y: 8 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ duration: 0.3 }}
              className={
                m.role === "user"
                  ? "ml-auto max-w-[80%] rounded-2xl rounded-br-md bg-brand-hover px-4 py-3 font-['Inter:Regular',sans-serif] text-[15px] text-white"
                  : "max-w-[85%] rounded-2xl rounded-bl-md border border-border-soft bg-white px-4 py-3 font-['Inter:Regular',sans-serif] text-[15px] text-ink shadow-[0_1px_4px_rgba(0,0,0,0.04)]"
              }
            >
              {m.content}
            </motion.div>
          ))}
          {isLoading && phase !== "test" && (
            <div className="max-w-[85%] rounded-2xl rounded-bl-md border border-border-soft bg-white px-4 py-3 font-['Inter:Regular',sans-serif] text-[15px] text-ink-muted shadow-[0_1px_4px_rgba(0,0,0,0.04)]">
              Pensando…
            </div>
          )}
          {error && <p className="font-['Inter:Regular',sans-serif] text-sm text-red-600">{error}</p>}

          {/* Fase 3 (Test) — used to be its own full-screen route step; now
              renders as a special message type inside this same chat
              timeline instead of swapping the whole screen out, so the
              person never leaves the conversation container. The dashed
              card wrapper (distinct from both the white assistant bubbles
              and the solid user bubbles above) is what marks it as a
              different kind of turn, on top of RiasecTest's own "Test
              vocacional" label. */}
          {phase === "test" && (
            <motion.div
              initial={{ opacity: 0, y: 8 }}
              animate={{ opacity: 1, y: 0 }}
              className="mx-auto w-full max-w-md rounded-3xl border-2 border-dashed border-brand-hover/30 bg-brand-hover/[0.04]"
            >
              <RiasecTest
                inline
                onComplete={(code) => {
                  setRiasecCode(code);
                  setPhase("resultado");
                }}
              />
            </motion.div>
          )}

          {/* Fase 4 (Resultado) — used to auto-render a Career Profile right
              here; now the closing chat message lands first and this button
              is what actually kicks off the roadmap (separate /api/roadmap
              call, see handleProcessResult), same "special turn inside the
              same thread" pattern as the Test card above. */}
          {resultadoReady && (
            <motion.div
              initial={{ opacity: 0, y: 8 }}
              animate={{ opacity: 1, y: 0 }}
              className="flex flex-col items-center gap-2 py-2"
            >
              <button
                type="button"
                onClick={handleProcessResult}
                disabled={roadmapState === "loading"}
                className="inline-flex items-center gap-2 rounded-pill bg-brand-hover px-6 py-3 font-['Plus_Jakarta_Sans:Medium',sans-serif] text-sm text-white transition-transform hover:scale-105 disabled:opacity-70"
              >
                {roadmapState === "loading" ? (
                  <>
                    <Loader2 className="h-4 w-4 animate-spin" />
                    Armando tu recorrido…
                  </>
                ) : (
                  <>
                    <Map className="h-4 w-4" />
                    Procesar resultado
                  </>
                )}
              </button>
              {roadmapState === "error" && roadmapError && (
                <p className="font-['Inter:Regular',sans-serif] text-xs text-red-600">{roadmapError}</p>
              )}
            </motion.div>
          )}
        </div>
      )}

      <div className="mx-auto w-full max-w-2xl shrink-0 px-6 pb-8">
        {/* While the RIASEC test card is active, the person interacts by
            tapping options up in the timeline, not by typing — so the chat
            input steps aside instead of sitting there as a second,
            confusing way to respond. */}
        {phase === "test" && (
          <p className="mb-2 text-center font-['Inter:Regular',sans-serif] text-xs text-ink-muted">
            Respondé el test de arriba para continuar
          </p>
        )}

        {/* CV status row — only while attaching is still an in-progress or
            failed action. Once it's "ready" AND the conversation has
            started, that state moves into the timeline above instead (see
            the chip rendered before the message list) so it isn't pinned
            here forever like a fake re-upload on every turn. Before the
            conversation starts, "ready" still shows here too (there's no
            timeline yet to put it in) with the option to remove it. */}
        {phase !== "test" && cv.status !== "idle" && (cv.status !== "ready" || !started.current) && (
          <div className="mb-2 flex items-center gap-2 px-1">
            {cv.status === "loading" && (
              <span className="flex items-center gap-1.5 font-['Inter:Regular',sans-serif] text-xs text-ink-muted">
                <Loader2 className="h-3.5 w-3.5 animate-spin" />
                Leyendo {cv.fileName}…
              </span>
            )}
            {cv.status === "ready" && (
              <span className="flex items-center gap-1.5 rounded-pill bg-white px-3 py-1.5 font-['Inter:Regular',sans-serif] text-xs text-ink shadow-[0_1px_4px_rgba(0,0,0,0.06)]">
                <FileText className="h-3.5 w-3.5 text-brand-hover" />
                {cv.fileName}
                <button
                  type="button"
                  onClick={() => setCv({ status: "idle" })}
                  aria-label="Quitar CV adjunto"
                  className="ml-1 text-ink-muted hover:text-ink"
                >
                  <X className="h-3.5 w-3.5" />
                </button>
              </span>
            )}
            {cv.status === "error" && (
              <span className="flex items-center gap-1.5 font-['Inter:Regular',sans-serif] text-xs text-red-600">
                <AlertCircle className="h-3.5 w-3.5" />
                {cv.message}
              </span>
            )}
          </div>
        )}

        <form onSubmit={handleSubmit} className={phase === "test" ? "pointer-events-none opacity-40" : undefined}>
          <div className="flex items-center gap-2 rounded-pill border border-border-soft bg-white p-2 shadow-[0_8px_24px_rgba(0,0,0,0.08)]">
            <span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full bg-brand-hover text-white">
              <Wand2 className="h-4 w-4" strokeWidth={2} />
            </span>
            <input
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder="Hablá con el Experto IA de Coderhouse"
              disabled={isLoading || phase === "test"}
              className="flex-1 bg-transparent px-1 py-2 font-['Inter:Regular',sans-serif] text-sm text-ink outline-none placeholder:text-ink-muted"
            />
            {!started.current && (
              <>
                <input
                  ref={fileInputRef}
                  type="file"
                  accept="application/pdf,.pdf"
                  onChange={handleFileSelect}
                  className="hidden"
                />
                <button
                  type="button"
                  onClick={() => fileInputRef.current?.click()}
                  disabled={cv.status === "loading"}
                  aria-label="Adjuntar CV (PDF)"
                  className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full text-ink-muted transition-colors hover:bg-ink/5 hover:text-ink disabled:opacity-40"
                >
                  <Plus className="h-4 w-4" />
                </button>
              </>
            )}
            <button
              type="submit"
              disabled={isLoading || !input.trim()}
              aria-label="Enviar"
              className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full bg-brand-hover text-white transition-transform hover:scale-105 disabled:opacity-40"
            >
              <Send className="h-4 w-4" />
            </button>
          </div>
        </form>
      </div>
    </LimboShell>
  );
}

function CategoryCarousel({ onSelect }: { onSelect: (label: string) => void }) {
  const trackRef = useRef<HTMLDivElement>(null);

  const scrollByCards = (dir: 1 | -1) => {
    trackRef.current?.scrollBy({ left: dir * 260, behavior: "smooth" });
  };

  return (
    <div className="relative mx-auto max-w-3xl">
      <div
        ref={trackRef}
        className="scrollbar-none flex gap-4 overflow-x-auto scroll-smooth px-1 py-1"
        style={{ scrollSnapType: "x proximity" }}
      >
        {CATEGORIES.map((c) => (
          <button
            key={c.label}
            type="button"
            onClick={() => onSelect(c.label)}
            style={{ scrollSnapAlign: "start" }}
            className="w-[150px] shrink-0 rounded-2xl border border-border-soft bg-white p-2.5 text-left shadow-[0_2px_10px_rgba(0,0,0,0.04)] transition-transform hover:scale-[1.03]"
          >
            <div className="mb-2 flex items-center justify-between gap-1">
              <span className="font-['Plus_Jakarta_Sans:SemiBold',sans-serif] text-xs leading-tight text-ink">
                {c.label}
              </span>
              {c.badge && (
                <span className="shrink-0 rounded-pill bg-brand-hover px-1.5 py-0.5 font-['Plus_Jakarta_Sans:SemiBold',sans-serif] text-[9px] text-white">
                  {c.badge}
                </span>
              )}
            </div>
            <img src={c.image} alt="" className="h-20 w-full rounded-xl object-cover" />
          </button>
        ))}
      </div>

      {/* Edge chevrons — peek over the first/last card to hint there's more
          to scroll to, same idea as the real site's Categories carousel. */}
      <button
        type="button"
        onClick={() => scrollByCards(-1)}
        aria-label="Ver categorías anteriores"
        className="absolute -left-4 top-1/2 hidden h-9 w-9 -translate-y-1/2 items-center justify-center rounded-full border border-border-soft bg-white text-ink shadow-[0_2px_10px_rgba(0,0,0,0.08)] sm:flex"
      >
        <ChevronLeft className="h-4 w-4" />
      </button>
      <button
        type="button"
        onClick={() => scrollByCards(1)}
        aria-label="Ver más categorías"
        className="absolute -right-4 top-1/2 hidden h-9 w-9 -translate-y-1/2 items-center justify-center rounded-full border border-border-soft bg-white text-ink shadow-[0_2px_10px_rgba(0,0,0,0.08)] sm:flex"
      >
        <ChevronRight className="h-4 w-4" />
      </button>
    </div>
  );
}

function LimboShell({ phase, children }: { phase: LimboPhase; children: React.ReactNode }) {
  return (
    <div className="bg-grid relative h-screen">
      {/* Floating overlay, not a flex sibling — this way the main column
          below centers against the full viewport width instead of just the
          leftover space next to it (which read as "shifted right"). */}
      <div className="absolute left-4 top-4 hidden lg:block">
        <LimboSidebar currentPhase={phase} />
      </div>

      <div className="grid h-full grid-rows-[auto_1fr_auto] overflow-hidden">
        <header className="flex items-center justify-between gap-3 px-5 py-4 sm:px-8">
          <Link
            to="/"
            className="flex items-center gap-2 text-ink-muted transition-colors hover:text-ink lg:hidden"
          >
            <ArrowLeft className="h-4 w-4" />
            <CoderhouseLogo className="h-4 w-auto" />
          </Link>
          <div className="ml-auto flex items-center gap-3">
            <Link
              to="/"
              className="rounded-pill bg-white px-4 py-2 font-['Inter:Regular',sans-serif] text-xs text-ink-muted shadow-[0_1px_4px_rgba(0,0,0,0.06)] transition-colors hover:text-ink sm:text-sm"
            >
              Omitir test
            </Link>
            <button
              type="button"
              aria-label="Configuración"
              className="flex h-9 w-9 items-center justify-center rounded-full bg-white text-ink-muted shadow-[0_1px_4px_rgba(0,0,0,0.06)]"
            >
              <Settings2 className="h-4 w-4" />
            </button>
            <div className="h-9 w-9 overflow-hidden rounded-full border border-border-soft bg-white shadow-[0_1px_4px_rgba(0,0,0,0.06)]">
              <img src="/community/avatar-1.png" alt="" className="h-full w-full object-cover" />
            </div>
          </div>
        </header>

        {children}
      </div>
    </div>
  );
}

